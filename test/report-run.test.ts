/** `src/gate/run.ts`: the product's sentence, then the checker's own last lines. */
function verifyFailDetail(command: string, tail: readonly string[]): string {
  return (
    `\`${command}\` exited 1. This is the WORKER's to fix — ruling 52's \`fail\`, which is ` +
    "why it is not `error` — and the item does not reach the integration branch." +
    // The trailing newline is the product's, and it is there even when the
    // checker said nothing at all.
    `\n${tail.join("\n")}`
  );
}

/**
 * `src/queue/execute.ts`: one sentence about THIS item, then four about ruling
 * 52 that are the same for every item that hit the same wall.
 */
function blockedBeforeMergeDetail(id: string): string {
  return (
    `item ${id} was never offered to the merge: verify. Ruling 52 ` +
    "has exactly one affirmative outcome and three blocking ones, and a blocking outcome keeps " +
    "the work OUT OF THE TREE rather than merely describing it — v1 merged its most delicate " +
    "change while its report said `review: not run (REVIEWER_FAILED)`. Its clone is retained " +
    "rather than deleted (ruling 63) and its work is reachable at its fetched ref for inspection."
  );
}

function item(id: string, blocking: boolean, tail: readonly string[] = []): RecordItem {
  return {
    id,
    number: Number(id.replace(/\D/g, "")) || 1,
    status: blocking ? "failed" : "integrated",
    kind: "write",
    agent: "codex",
    model: "gpt-5.6-sol",
    // Realistic rather than minimal: a real item carries three checks and each
    // one carries the checker's own words, and a fixture of one-word checks
    // would make the cap look roomier than it is.
    checks: blocking
      ? [
          { name: "worker", outcome: "pass", blocking: false, detail: "codex took one turn and stopped with end_turn" },
          {
            name: `verify ${id}`,
            outcome: "fail",
            blocking: true,
            detail: verifyFailDetail("/w/failing-verify", tail),
          },
          // What the product records for an item that never reached the merge:
          // a BLOCKING `not-run` with the qualifier inside the result. The old
          // fixture had this check passing, which is a shape a failing item
          // never has.
          {
            name: `integrate item ${id}`,
            outcome: "not-run",
            blocking: true,
            qualifier: "blocked before the merge",
            detail: blockedBeforeMergeDetail(id),
          },
        ]
      : [
          { name: "worker", outcome: "pass", blocking: false, detail: "codex took one turn and stopped with end_turn" },
          { name: "review", outcome: "pass", blocking: true, qualifier: "cross-vendor", detail: "qwen reviewed codex's diff" },
          { name: `integrate item ${id}`, outcome: "pass", blocking: false, detail: "1 path merged cleanly" },
        ],
  };
}

/**
 * Where the report starts talking about `id`, or `-1`.
 *
 * ANCHORED AT `^<indent><id>:`, and that is the whole reason this helper exists
 * rather than `report.includes(id)`. The bar's fifty-item fixture fails
 * `fifty-4`, `fifty-18` and `fifty-43`, and `"fifty-43".includes("fifty-4")` is
 * TRUE — so a cap that dropped `fifty-4` outright would still satisfy a
 * containment test, because a different item's id contains it. The one item
 * likeliest to be dropped first is the one such a test cannot miss.
 */
function headLineIndex(report: string, id: string): number {
  const head = new RegExp(`^\\s*${id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}:\\s`);
  return report.split("\n").findIndex((line) => head.test(line));
}

/**
 * The BLOCK the report devotes to one item: its head line and the indented lines
 * under it, up to the next item or the first line at column zero.
 *
 * Column zero is where the run-level sections are written (`the merged result:`,
 * `the run:`, `review:`), so it is the boundary the product itself draws — and
 * the boundary a reader parsing by indentation, or `bar/lib/item11-structure.ts`
 * doing the same, will draw too.
 */
function itemBlockOf(report: string, id: string, allIds: readonly string[]): string | undefined {
  const lines = report.split("\n");
  const start = headLineIndex(report, id);
  if (start === -1) return undefined;
  const nextItem = allIds
    .filter((other) => other !== id)
    .map((other) => headLineIndex(report, other))
    .filter((index) => index > start);
  const unindented = lines.findIndex((line, index) => index > start && /^\S/.test(line));
  const ends = [...nextItem, unindented === -1 ? lines.length : unindented, lines.length].filter(
    (index) => index > start,
  );
  return lines.slice(start, Math.min(...ends)).join("\n");
}

/**
 * Every check of a FAILING item that is not inside that item's own block, named.
 *
 * THE GUARD, AND IT IS THE ONE THE PRODUCT FAILED. MEASURED on 2026-08-19
 * against `bun 1.3.14`: six items whose checker printed twelve lines produced
 * *"18 check(s) recorded; absent from their item's block: pressure-1/integrate
 * item 1: not-run; …"* — the checks were in the bytes, and outside the item they
 * belong to, because a multi-line detail was indented on its first line only and
 * ended the block at column zero.
 *
 * It returns NAMES rather than a count on purpose. A count answers "how many"
 * and the question ruling 52 asks is "WHICH", and a guard that cannot say which
 * cannot be shown to fire on the right thing.
 */
function checksOutsideTheirBlocks(report: string, items: readonly RecordItem[]): string[] {
  const ids = items.map((entry) => entry.id);
  const failing = items.filter((entry) => entry.checks.some((check) => check.blocking && check.outcome !== "pass"));
  const absent: string[] = [];
  for (const entry of failing) {
    const block = itemBlockOf(report, entry.id, ids);
    for (const check of entry.checks) {
      if (block === undefined || !block.includes(`${check.name}: ${check.outcome}`)) {
        absent.push(`${entry.id}/${check.name}: ${check.outcome}`);
      }
    }
  }
  return absent;
}

function record(items: RecordItem[], refusedDelegations = 0): RunRecord {
  return {
    runId: "r1",
    integrationRef: "refs/heads/brigadier/r1",
    integrationSha: "1".repeat(40),
    base: { ref: "refs/brigadier/r1/base", sha: "0".repeat(40) },
    runRoot: "/home/x/.brigadier",
    bindingFilter: "desirability",
    workers: 3,
    refusedDelegations,
    items,
  };
}

